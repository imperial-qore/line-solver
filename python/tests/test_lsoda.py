# Test 7: Oregonator (stiff chemical oscillator)
# ============================================================================
def test_oregonator():
    """Oregonator model for Belousov-Zhabotinsky reaction.
    3 equations, stiff. Requires many steps.
    Verify solver can handle it (with increased max_steps).
    """
    def f(t, y, ydot, data):
        s = 77.27
        w = 0.161
        q = 8.375e-6
        ydot[0] = s * (y[1] - y[0]*y[1] + y[0] - q*y[0]*y[0])
        ydot[1] = (-y[1] - y[0]*y[1] + y[2]) / s
        ydot[2] = w * (y[0] - y[2])

    y0 = [1.0, 2.0, 3.0]
    t_eval = [50.0, 100.0, 200.0, 300.0, 360.0]

    result = lsoda(f, y0, (0.0, 360.0), t_eval=t_eval,
                   rtol=[1e-6]*3, atol=[1e-8]*3, max_steps=5000)

    ok = result.success
    if not ok:
        print(f"  FAIL: solver failed - {result.message}")
        return False

    # Verify solution is positive and bounded
    for idx, t in enumerate(t_eval):
        yv = result.y[idx + 1]
        if any(yv < -1e-8):
            print(f"  FAIL: negative values at t={t}: {yv}")
            ok = False

    print(f"  PASS: nst={result.nst}, nfe={result.nfe}, nje={result.nje}")
    return ok


