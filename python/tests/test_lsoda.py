# Test 3: Linear 2D system (exact solution available)
# ============================================================================
def test_linear_2d():
    """dy1/dt = -0.04*y1, dy2/dt = 0.04*y1 - 0.0004*y2.
    y1(0)=100, y2(0)=0.
    Exact: y1(t) = 100*exp(-0.04*t)
           y2(t) = 100*(0.04/(0.04-0.0004))*(exp(-0.0004*t) - exp(-0.04*t))
    """
    def f(t, y, ydot, data):
        ydot[0] = -0.04 * y[0]
        ydot[1] = 0.04 * y[0] - 0.0004 * y[1]

    y0 = [100.0, 0.0]
    t_eval = [10.0, 25.0, 50.0, 100.0, 200.0]

    # C reference output
    expected = [
        (1e+01, 6.703200486744036e+01, 3.289777178480690e+01),
        (2.5e+01, 3.678794391922581e+01, 6.284549439968792e+01),
        (5e+01, 1.353352809382181e+01, 8.533973660288261e+01),
        (1e+02, 1.831563895789600e+00, 9.519937375701294e+01),
        (2e+02, 3.354626444786475e-02, 9.321019027698564e+01),
    ]

    ok = _run_parity_test("Linear2D", f, y0, (0.0, 200.0), t_eval,
                          rtol=[1e-8]*2, atol=[1e-10]*2,
                          expected=expected, check_rtol=1e-6)

    # Verify against exact solution
    if ok:
        result = lsoda(f, y0, (0.0, 200.0), t_eval=t_eval, rtol=[1e-8]*2, atol=[1e-10]*2)
        max_err = 0.0
        for idx, t in enumerate(t_eval):
            y1_exact = 100.0 * np.exp(-0.04 * t)
            k1, k2 = 0.04, 0.0004
            y2_exact = 100.0 * (k1 / (k1 - k2)) * (np.exp(-k2 * t) - np.exp(-k1 * t))
            for j, ye in enumerate([y1_exact, y2_exact]):
                if abs(ye) > 1e-10:
                    err = abs(result.y[idx + 1][j] - ye) / abs(ye)
                    max_err = max(max_err, err)
        if max_err < 1e-6:
            print(f"  Exact solution check: PASS (max_rel_err={max_err:.2e})")
        else:
            print(f"  Exact solution check: FAIL (max_rel_err={max_err:.2e})")
            ok = False
    return ok


