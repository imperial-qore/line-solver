    max_diff = 0.0
    for idx in range(len(r1.t)):
        diff = np.max(np.abs(r1.y[idx] - r2.y[idx]))
        max_diff = max(max_diff, diff)

    ok = max_diff < 1e-14
    status = "PASS" if ok else "FAIL"
    print(f"  {status}: max diff between scalar/array tolerances = {max_diff:.2e}")
    return ok


