"""
Parity tests for the pure Python LSODA port against the C liblsoda reference.

All expected values are generated by compiling and running liblsoda
(sdwfrost/liblsoda) with the same problem parameters and tolerances,
using full-precision (%.15e) output.

Tests cover:
  1. Robertson chemical kinetics (stiff, 3 eqs, classic LSODA benchmark)
  2. Exponential decay (trivial nonstiff, 1 eq, exact solution known)
  3. Linear 2D system (mildly stiff, 2 eqs, exact solution known)
  4. Lotka-Volterra predator-prey (nonstiff oscillator, 2 eqs)
  5. HIRES photochemistry (moderately stiff, 8 eqs)
  6. Van der Pol oscillator (very stiff mu=1000, 2 eqs)
  7. Oregonator (stiff chemical oscillator, 3 eqs)
  8. Conservation law verification (Robertson y1+y2+y3 = 1)
  9. Scalar tolerance interface
"""
import sys
import os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

import numpy as np
