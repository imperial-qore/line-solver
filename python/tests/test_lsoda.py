# Test 10: odeint convenience interface vs lsoda()
# ============================================================================
def test_odeint_parity():
    """Verify lsoda_odeint gives same results as lsoda for decay problem."""
    def f_lsoda(t, y, ydot, data):
        ydot[0] = -y[0]
        ydot[1] = -2.0 * y[1]

    def f_odeint(t, y):
        return [-y[0], -2.0 * y[1]]

    y0 = [1.0, 1.0]
    t_eval = np.array([0.0, 0.5, 1.0, 2.0, 5.0])

    r1 = lsoda(f_lsoda, y0, (0.0, 5.0), t_eval=t_eval[1:], rtol=1e-8, atol=1e-10)
    r2 = lsoda_odeint(f_odeint, y0, t_eval, rtol=1e-8, atol=1e-10)

    if not r1.success or not r2.success:
        print(f"  FAIL: solver failed")
        return False

    # Both should have same number of output points
    max_diff = 0.0
    for idx in range(min(len(r1.y), len(r2.y))):
        diff = np.max(np.abs(r1.y[idx] - r2.y[idx]))
        max_diff = max(max_diff, diff)

    # Also check against exact solution
    max_exact_err = 0.0
    for idx, t in enumerate(t_eval):
        y_exact = np.array([np.exp(-t), np.exp(-2.0 * t)])
        err = np.max(np.abs(r2.y[idx] - y_exact))
        max_exact_err = max(max_exact_err, err)

    ok = max_diff < 1e-12 and max_exact_err < 1e-6
    status = "PASS" if ok else "FAIL"
    print(f"  {status}: lsoda/odeint diff={max_diff:.2e}, exact err={max_exact_err:.2e}")
    return ok


