# Test 2: Exponential decay (nonstiff, exact solution)
# ============================================================================
def test_exponential_decay():
    """dy/dt = -y, y(0)=1. Exact: y(t) = exp(-t)."""
    def f(t, y, ydot, data):
        ydot[0] = -y[0]

    y0 = [1.0]
    t_eval = [0.5, 1.0, 2.0, 5.0, 10.0]

    # C reference output
    expected = [
        (5e-01, 6.065306706955518e-01),
        (1e+00, 3.678794480345809e-01),
        (2e+00, 1.353352828204701e-01),
        (5e+00, 6.737947209171920e-03),
        (1e+01, 4.539994917152099e-05),
    ]

    ok = _run_parity_test("ExponentialDecay", f, y0, (0.0, 10.0), t_eval,
                          rtol=[1e-8], atol=[1e-10],
                          expected=expected, check_rtol=1e-6)

    # Also verify against exact solution
    if ok:
        result = lsoda(f, y0, (0.0, 10.0), t_eval=t_eval, rtol=[1e-8], atol=[1e-10])
        for idx, t in enumerate(t_eval):
            exact = np.exp(-t)
            err = abs(result.y[idx + 1][0] - exact) / exact
            if err > 1e-6:
                print(f"  FAIL vs exact at t={t}: err={err:.2e}")
                ok = False
        if ok:
            print("  Exact solution check: PASS")
    return ok


