# ============================================================================
# Tolerance for parity checks
# ============================================================================
# Python and C may differ slightly due to floating-point evaluation order.
# We use relative tolerance for large values and absolute for small values.
def _check_parity(y_got, y_exp, rtol=1e-4, atol=1e-10):
    """Check if y_got matches y_exp within tolerances.
    Returns (ok, max_rel_err, max_abs_err).
    """
    max_rel = 0.0
    max_abs = 0.0
    ok = True
    for i in range(len(y_exp)):
        ae = abs(y_got[i] - y_exp[i])
        max_abs = max(max_abs, ae)
        if abs(y_exp[i]) > atol:
            re = ae / abs(y_exp[i])
            max_rel = max(max_rel, re)
            if re > rtol:
                ok = False
        else:
            if ae > atol:
                ok = False
    return ok, max_rel, max_abs


def _run_parity_test(name, f, y0, t_span, t_eval, rtol, atol,
                     expected, max_steps=500, check_rtol=1e-4, check_atol=1e-10):
    """Run a parity test against C reference values.
    expected: list of (t, y0, y1, ...) tuples with full-precision C output.
    Returns True if all points match.
    """
    result = lsoda(f, y0, t_span, t_eval=t_eval, rtol=rtol, atol=atol,
                   max_steps=max_steps)
    if not result.success:
        print(f"  FAIL: solver failed - {result.message}")
        return False

    neq = len(y0)
    all_pass = True
    max_rel_total = 0.0
    max_abs_total = 0.0

    for idx, exp_row in enumerate(expected):
        t_exp = exp_row[0]
        y_exp = list(exp_row[1:])
        y_got = result.y[idx + 1]  # +1 because y[0] is initial state

        ok, max_rel, max_abs = _check_parity(y_got, y_exp, check_rtol, check_atol)
        max_rel_total = max(max_rel_total, max_rel)
        max_abs_total = max(max_abs_total, max_abs)

        if not ok:
            all_pass = False
            print(f"  FAIL at t={t_exp:.4e}: max_rel={max_rel:.2e}")
            for j in range(neq):
                if abs(y_exp[j]) > check_atol:
                    re = abs(y_got[j] - y_exp[j]) / abs(y_exp[j])
                else:
                    re = abs(y_got[j] - y_exp[j])
                flag = " <--" if re > check_rtol else ""
                print(f"    y[{j}]: got={y_got[j]:.15e} exp={y_exp[j]:.15e} err={re:.2e}{flag}")

    status = "PASS" if all_pass else "FAIL"
    print(f"  {status}: max_rel_err={max_rel_total:.2e}, nst={result.nst}, nfe={result.nfe}, nje={result.nje}")
    return all_pass


