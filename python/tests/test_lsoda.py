def test_scalar_tolerances():
    """Verify that scalar rtol/atol work the same as per-component arrays."""
    def f(t, y, ydot, data):
        ydot[0] = -0.04 * y[0]
        ydot[1] = 0.04 * y[0] - 0.0004 * y[1]

    y0 = [100.0, 0.0]
    t_eval = [10.0, 50.0, 100.0]

    # Run with scalar tolerances
    r1 = lsoda(f, y0, (0.0, 100.0), t_eval=t_eval, rtol=1e-8, atol=1e-10)
    # Run with array tolerances (same values)
    r2 = lsoda(f, y0, (0.0, 100.0), t_eval=t_eval, rtol=[1e-8]*2, atol=[1e-10]*2)

