# Test 6: Van der Pol oscillator (very stiff, mu=1000)
# ============================================================================
def test_vanderpol():
    """Van der Pol oscillator with mu=1000 (very stiff).
    dy1/dt = y2, dy2/dt = mu*(1-y1^2)*y2 - y1.
    No C reference (too large), but verify solver completes successfully
    and solution stays bounded.
    """
    mu = 1000.0

    def f(t, y, ydot, data):
        ydot[0] = y[1]
        ydot[1] = mu * (1.0 - y[0] * y[0]) * y[1] - y[0]

    y0 = [2.0, 0.0]
    t_end = 3000.0
    t_eval = np.linspace(0, t_end, 100)[1:]

    result = lsoda(f, y0, (0.0, t_end), t_eval=t_eval,
                   rtol=1e-6, atol=1e-8, max_steps=100000)

    ok = result.success
    if not ok:
        print(f"  FAIL: solver failed - {result.message}")
        return False

    # Check solution stays bounded (Van der Pol has limit cycle with |y1| <= ~2.1)
    y_max = np.max(np.abs(result.y[:, 0]))
    if y_max > 2.5:
        print(f"  FAIL: y1 exceeded expected bound: max|y1|={y_max:.4f}")
        ok = False

    print(f"  PASS: nst={result.nst}, nfe={result.nfe}, nje={result.nje}, max|y1|={y_max:.4f}")
    return ok


