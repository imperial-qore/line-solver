# Test 1: Robertson chemical kinetics (stiff)
# ============================================================================
def test_robertson():
    """Robertson problem: classic stiff ODE benchmark (3 eqs).
    dy1/dt = -0.04*y1 + 1e4*y2*y3
    dy2/dt = 0.04*y1 - 1e4*y2*y3 - 3e7*y2^2
    dy3/dt = 3e7*y2^2
    """
    def f(t, y, ydot, data):
        ydot[0] = 1.0e4 * y[1] * y[2] - 0.04 * y[0]
        ydot[2] = 3.0e7 * y[1] * y[1]
        ydot[1] = -(ydot[0] + ydot[2])

    y0 = [1.0, 0.0, 0.0]
    t_eval = [0.4 * 10.0 ** i for i in range(12)]

    # C reference output (%.15e precision)
    expected = [
        (4e-01, 9.851712049052344e-01, 3.386380058450371e-05, 1.479493129418126e-02),
        (4e+00, 9.055332934421416e-01, 2.240655242773938e-05, 9.444430000543071e-02),
        (4e+01, 7.158403474138746e-01, 9.186333848221152e-06, 2.841504662522774e-01),
        (4e+02, 4.505250299518244e-01, 3.222963773719375e-06, 5.494717470844018e-01),
        (4e+03, 1.831975696546021e-01, 8.941773261377527e-07, 8.168015361680721e-01),
        (4e+04, 3.898729244522436e-02, 1.621939581471608e-07, 9.610125453607797e-01),
        (4e+05, 4.936362159709025e-03, 1.984220853834811e-08, 9.950636179980765e-01),
        (4e+06, 5.161832921225141e-04, 2.065786542448266e-09, 9.994838146420849e-01),
        (4e+07, 5.179803644367760e-05, 2.072026913293681e-10, 9.999482017563474e-01),
        (4e+08, 5.283686292063946e-06, 2.113485306887202e-11, 9.999947162925692e-01),
        (4e+09, 4.658646268319763e-07, 1.863459326277758e-12, 9.999995341335010e-01),
        (4e+10, 1.431681921554496e-08, 5.726732909838437e-14, 9.999999856831133e-01),
    ]

    # Robertson uses rtol=1e-4 for integration. The C and Python FP
    # evaluation paths diverge at extreme time scales (t=4e10) for
    # near-zero values (~1e-8), so we allow 0.5% relative tolerance
    # which is well within the integration accuracy.
    return _run_parity_test("Robertson", f, y0, (0.0, t_eval[-1]), t_eval,
                            rtol=[1e-4]*3, atol=[1e-6, 1e-10, 1e-6],
                            expected=expected, check_rtol=5e-3, check_atol=1e-8)


