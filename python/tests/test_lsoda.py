# Test 12: Large system (50 coupled equations)
# ============================================================================
def test_large_system():
    """50-equation coupled decay chain: dy_i/dt = -alpha_i * y_i + alpha_{i-1} * y_{i-1}.
    Tests that dgefa/dgesl work correctly for larger matrices.
    """
    N = 50
    alphas = np.linspace(0.01, 1.0, N)

    def f(t, y, ydot, data):
        ydot[0] = -alphas[0] * y[0]
        for i in range(1, N):
            ydot[i] = alphas[i - 1] * y[i - 1] - alphas[i] * y[i]

    y0 = np.zeros(N)
    y0[0] = 1.0
    t_eval = [1.0, 10.0, 100.0]

    result = lsoda(f, y0, (0.0, 100.0), t_eval=t_eval,
                   rtol=1e-6, atol=1e-8, max_steps=5000)

    if not result.success:
        print(f"  FAIL: solver failed - {result.message}")
        return False

    # Conservation: sum of all y_i should be 1 (closed chain) or decreasing
    # Actually this is an open chain (last element decays), so sum < 1
    # Just check positivity and boundedness
    ok = True
    for idx in range(len(result.t)):
        yv = result.y[idx]
        if np.any(yv < -1e-8):
            print(f"  FAIL: negative values at t={result.t[idx]}")
            ok = False
        if np.any(yv > 1.1):
            print(f"  FAIL: values exceeded initial at t={result.t[idx]}")
            ok = False

    status = "PASS" if ok else "FAIL"
    print(f"  {status}: nst={result.nst}, nfe={result.nfe}, nje={result.nje}")
    return ok


