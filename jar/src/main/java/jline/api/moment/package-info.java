/**
 * Moment conversion algorithms for discrete distributions.
 *
 * <p>This package provides the one-to-one conversions between the moment
 * families of a discrete random variable N: power (raw) moments, factorial
 * moments, upward-factorial moments, binomial moments, negative-binomial
 * moments and central moments. The conversions are driven by the combinatorial
 * triangles of the Stirling numbers of the first and second kind, the Stirling
 * cycle numbers and the Lah numbers.
 *
 * <p>Reference:
 * A. Heindl and A. van de Liefvoort. Moment conversions for discrete
 * distributions. PMCCS, 2003.
 *
 * @since LINE 2.0
 */
