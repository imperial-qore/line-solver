% The fluid solver returns the CDF on ITS OWN time grid, and how finely the
% integrator reports is an implementation detail, not part of the answer:
% measured 2026-08-25 it is 7381 and 9699 points against the 145 and 159
% recorded here. Comparing the raw matrices therefore fails on SHAPE -- the
% subtraction throws, and the catch reports it in the same words it would use
% for a curve that had moved, which is how this read as a numeric regression.
% Sample the returned curve at the RECORDED times instead. The ground truth
% below is untouched; on that grid the two agree to 2.8e-4 (RDfluid{1}) and
% 6.9e-5 (RDfluid{2}), the residual being the 4-decimal rounding of the values
% stored here. Column 1 is the CDF, column 2 the time, as the plot block of
% tut08_respt_cdf.m reads them. RDsim above is spared this because it
% subsamples the simulated curve rather than comparing it raw: LDES returns
% 5002 and 4998 points at 1e4 samples, so 1:500:end leaves 11 and 10 rows.
[tf1, if1] = unique(RDfluid{1}(:,2), 'first');
F1 = interp1(tf1, RDfluid{1}(if1,1), RDfluid1(:,2), 'linear', 'extrap');
try
    assert(max(abs(F1-RDfluid1(:,1)))<TOL,sprintf('%s changed on RDfluid{1}.',testName));
catch me
    gsFailures{end+1} = me.message;
    fprintf('Assertion failed on RDfluid{1} in %s.\n',testName)
end

[tf2, if2] = unique(RDfluid{2}(:,2), 'first');
