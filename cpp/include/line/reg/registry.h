inline const ApiEntry* find_api(const std::string& name) {
    const auto& reg = api_registry();
    auto it = std::find_if(reg.begin(), reg.end(),
                           [&](const ApiEntry& e) { return e.name == name; });
    return it == reg.end() ? nullptr : &*it;
}

inline bool api_supports(const ApiEntry& e, Arith a) {
    return std::find(e.arith.begin(), e.arith.end(), a) != e.arith.end();
}

