/** Number of tabulated grid points, including t = 0 (me_sample.m GRIDPTS). */
const std::size_t grid_points = 1000;
/** Cap on horizon doublings (me_sample.m MAXDBL). */
const int max_doublings = 40;
/** Survival mass left beyond the horizon (me_sample.m TAILTOL). */
const double tail_mass_tol = 1e-12;
/** Newton refinements applied to each inverted quantile (me_sample.m NEWTON). */
const int newton_steps = 3;
/** Largest ||A||*d a single Taylor substep handles. */
const double taylor_theta = 0.5;
/** Substep cap before falling back to a matrix exponential. */
const int taylor_max_steps = 64;
/** Taylor terms per substep. */
const int taylor_max_terms = 30;

/** w <- w M, the row-vector product the grid and the Taylor walk both need. */
template <class T>
std::vector<T> vec_times_mat(const std::vector<T>& w, const Matrix<T>& M) {
    const std::size_t n = w.size();
    std::vector<T> out(n, num_traits<T>::from_int(0));
    for (std::size_t j = 0; j < n; ++j)
        for (std::size_t i = 0; i < n; ++i) out[j] += w[i] * M(i, j);
    return out;
}

/**
 * w exp(A d) by a scaled Taylor series on the VECTOR.
 *
 * Falls back to a matrix exponential when the substep count would exceed the
 * cap, which is the only regime where the series is the more expensive of the
 * two.
 */
template <class T>
std::vector<T> expm_propagate(const std::vector<T>& w, const Matrix<T>& A, double norm_a, double d) {
    const std::size_t n = w.size();
    if (!(d > 0.0)) return w;
    int steps = 1;
    const double theta = norm_a * d;
    if (theta > taylor_theta) {
        steps = static_cast<int>(std::ceil(theta / taylor_theta));
        if (steps > taylor_max_steps)
            return vec_times_mat(w, expm(A, num_traits<T>::from_double(d)));
    }
    const double ds = d / steps;
    std::vector<T> acc = w;
    for (int s = 0; s < steps; ++s) {
        std::vector<T> term = acc, next = acc;
        for (int k = 1; k <= taylor_max_terms; ++k) {
            term = vec_times_mat(term, A);
            const T c = num_traits<T>::from_double(ds / k);
            double max_term = 0.0, max_acc = 0.0;
            for (std::size_t j = 0; j < n; ++j) {
                term[j] = T(term[j] * c);
                next[j] += term[j];
                const double at = std::fabs(num_traits<T>::to_double(term[j]));
                if (at > max_term) max_term = at;
                const double an = std::fabs(num_traits<T>::to_double(next[j]));
                if (an > max_acc) max_acc = an;
            }
            if (max_term <= 1e-18 * (max_acc > 1e-300 ? max_acc : 1e-300)) break;
        }
        acc = next;
    }
    return acc;
}

/**
 * The dominant (least negative) eigenvalue of D0, which governs the tail decay.
 *
 * The spectrum is taken in double precision whatever T is: the extrapolation it
 * feeds is a tail approximation, so its own last digits do not matter, and the
 * fallback -1/mean is what the reference uses when the decomposition fails.
 */
template <class T>
double dominant_rate(const Matrix<T>& A, double mean) {
    double eta = -std::numeric_limits<double>::infinity();
    const std::size_t n = A.rows();
    Matrix<double> Ad(n, n);
    for (std::size_t i = 0; i < n; ++i)
        for (std::size_t j = 0; j < n; ++j) Ad(i, j) = num_traits<T>::to_double(A(i, j));
    try {
        const std::vector<std::complex<double> > ev = eig_values(Ad);
        for (std::size_t i = 0; i < ev.size(); ++i)
            if (ev[i].real() > eta) eta = ev[i].real();
    } catch (const std::exception&) {
        eta = -std::numeric_limits<double>::infinity();
    }
    if (!(eta < 0.0) || !std::isfinite(eta)) eta = (mean > 0.0) ? -1.0 / mean : -1.0;
    return eta;
}

