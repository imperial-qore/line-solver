/** What `tikz_view` produced. */
struct TikzViewResult {
    std::string path;     ///< the compiled PDF, or the `.tex` saved when it could not be compiled
    bool compiled = false;  ///< `path` is a PDF
    bool opened = false;    ///< a viewer was started on it
};

/**
 * `MNetwork.tikzView` (`TikZExporter.display`). With pdflatex, compile the
 * document into a fresh `line_tikz_*` directory that is LEFT IN PLACE (the
 * viewer reads it after this returns) and, when `open_viewer`, start a PDF
 * viewer on it. Without pdflatex, or when compilation fails, save the source
 * to `network-diagram.tex` in the working directory, as the JAR does, and say
 * so on stdout. Nothing is thrown for a missing tool; the result says what exists.
 */
template <class M>
TikzViewResult tikz_view(M& model, const TikzOptions& opt = TikzOptions(), bool open_viewer = true) {
    TikzViewResult res;
    const std::string tex = to_tikz(model, opt);
    if (tikz_pdflatex_available()) {
        try {
            util::TempDir dir("tikz");
            res.path = tikz_detail::compile_pdf(tex, dir);
            dir.keep();
            res.compiled = true;
        } catch (const Error& e) {
            std::cerr << "Failed to generate visualization: " << e.what() << "\n";
        }
    }
    if (!res.compiled) {
        res.path = "network-diagram.tex";
        tikz_detail::write_text(res.path, tex);
        std::cout << "TikZ code saved to: " << res.path << "\nCompile manually with: pdflatex " << res.path
                  << "\n";
        return res;
    }
    if (open_viewer) {
        res.opened = tikz_detail::display_pdf(res.path);
        if (res.opened)
            std::cout << "Opened diagram for: " << tikz_detail::model_name(model) << "\n";
        else
            std::cout << "Could not open PDF viewer. File saved at: " << res.path << "\n";
    }
    return res;
}

