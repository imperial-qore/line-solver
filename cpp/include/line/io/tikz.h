/**
 * @file
 * @ingroup line_io
 * Port of `jline.io.tikz.TikZExporter`, the network diagram behind MATLAB's
 * `MNetwork.toTikZ`, `exportTikZToFile`, `exportTikZ` and `tikzExportPNG`.
 *
 * `to_tikz` returns a complete `standalone` LaTeX document: the JAR's preamble
 * and styles, one TikZ node per network node at its layered-layout position
 * (tikz/tikz_layout.h), then one arrow per connection, routed around the nodes
 * in its way (tikz/tikz_edge_router.h). The text is the JAR's for the same
 * model and options, byte for byte.
 *
 * EDGE ORDER. Source nodes in model order (the drawn ones), and for each its
 * targets in ascending node index, the order of the connection-matrix row,
 * whether they are reached directly or through hidden class switches. The JAR
 * writes the same order (a node-index `TreeSet`, since it replaced a `HashSet`
 * of identity-hashed nodes), and so does MATLAB, which draws through the JAR.
 *
 * Every arrow is unlabelled: `generateTikZ` passes a NaN probability for every
 * edge, so `show_routing_prob` never takes effect, here as there.
 *
 * `export_tikz` and `tikz_export_png` shell out to `pdflatex` (and `pdftoppm`,
 * from poppler-utils) through `util::capture`; `tikz_pdflatex_available` says
 * whether the first can run. `tikz_view` is `MNetwork.tikzView` (the JAR's
 * `TikZExporter.display`): it compiles the PDF into a directory it leaves in
 * place and opens it in a standalone viewer when asked to and one is on PATH.
 */

