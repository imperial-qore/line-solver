/**
 * Assemble the drift terms of a net.
 *
 * @param sn a model whose nodes are Places, Transitions, Sources and Sinks only
 */
template <class T>
inline PetriTerms petri_build_terms(const qn::NetworkStruct<T>& sn) {
    PetriTerms t;
    t.I = sn.nodes.size();
    t.K = sn.nclasses;
    t.M = sn.nstations;
    t.names_node.resize(t.I);
    for (std::size_t i = 0; i < t.I; ++i) t.names_node[i] = sn.nodes[i].name;
    for (std::size_t i = 1; i <= t.I; ++i) {
        if (sn.nodes[i - 1].nodetype == lang::NodeType::Place) t.places.push_back(i);
        else if (sn.nodes[i - 1].nodetype == lang::NodeType::Transition) t.transitions.push_back(i);
    }

    // ---- the initial marking ------------------------------------------------
    // A Place's DECLARED marking wins; absent one, each closed class loads its
    // reference station, which is the rule spn_sinvariants and the exact SPN
    // engines use. An infinite marking is refused rather than integrated.
    t.m0full.assign(t.I, std::vector<double>(t.K, 0.0));
    for (std::size_t pi = 0; pi < t.places.size(); ++pi) {
        const std::size_t ind = t.places[pi];
        const typename std::map<std::size_t, std::vector<T>>::const_iterator im =
            sn.initmarking.find(ind);
        if (im == sn.initmarking.end()) continue;
        for (std::size_t k = 0; k < t.K && k < im->second.size(); ++k) {
            const double v = num_traits<T>::to_double(im->second[k]);
            if (std::isinf(v))
                throw InputError("fluid_petri_terms: place " + t.names_node[ind - 1] +
                                 " holds an infinite initial marking of class " +
                                 std::to_string(k + 1));
            t.m0full[ind - 1][k] = v;
        }
    }
    bool any_declared = false;
    for (std::size_t pi = 0; pi < t.places.size() && !any_declared; ++pi)
        any_declared = (sn.initmarking.find(t.places[pi]) != sn.initmarking.end());
    if (!any_declared) {
        for (std::size_t r = 0; r < sn.classes.size(); ++r) {
            const double njobs = num_traits<T>::to_double(sn.classes[r].population);
            if (!(njobs > 0.0) || !std::isfinite(njobs)) continue;
            if (sn.classes[r].refstat < 1 || sn.classes[r].refstat > sn.station_to_node.size())
                continue;
            const std::size_t ref_node = sn.station_to_node[sn.classes[r].refstat - 1];
            if (ref_node >= 1 && ref_node <= t.I &&
                sn.nodes[ref_node - 1].nodetype == lang::NodeType::Place)
                t.m0full[ref_node - 1][r] += njobs;
        }
    }

    // ---- which (place, class) pairs carry a coordinate ----------------------
    std::vector<std::vector<bool>> touched(t.I, std::vector<bool>(t.K, false));
    for (std::size_t ti = 0; ti < t.transitions.size(); ++ti) {
        const std::size_t ind = t.transitions[ti];
        const typename std::map<std::size_t, qn::TransitionParam<T>>::const_iterator it =
            sn.transparam.find(ind);
        if (it == sn.transparam.end()) continue;
        const qn::TransitionParam<T>& tp = it->second;
        for (std::size_t m = 0; m < tp.nmodes; ++m) {
            const std::vector<std::vector<double>> en =
                terms_detail::pad(tp.enabling[m], t.I, t.K, 0.0);
            const std::vector<std::vector<double>> fir =
                terms_detail::pad(tp.firing[m], t.I, t.K, 0.0);
            const std::vector<std::vector<double>> inh = terms_detail::pad(
                tp.inhibiting[m], t.I, t.K, std::numeric_limits<double>::infinity());
            for (std::size_t i = 0; i < t.I; ++i)
                for (std::size_t k = 0; k < t.K; ++k)
                    if (en[i][k] > 0 || fir[i][k] != 0 ||
                        (!std::isinf(inh[i][k]) && inh[i][k] > 0))
                        touched[i][k] = true;
        }
    }

    // An arrival makes its target a coordinate even when no arc mentions it.
    struct SrcArr {
        std::size_t snd, r, qnd, l;
    };
    std::vector<SrcArr> src_arr;
    for (std::size_t ind = 1; ind <= t.I; ++ind) {
        if (sn.nodes[ind - 1].nodetype != lang::NodeType::Source) continue;
        const std::size_t ist = sn.nodes[ind - 1].station;
        if (ist < 1) continue;
        for (std::size_t r = 0; r < t.K; ++r) {
            const double lambda = num_traits<T>::to_double(sn.rates(ist - 1, r));
            if (std::isnan(lambda) || lambda <= 0) continue;
            for (std::size_t pi = 0; pi < t.places.size(); ++pi) {
                const std::size_t jnd = t.places[pi];
                for (std::size_t s = 0; s < t.K; ++s) {
                    const double p = num_traits<T>::to_double(
                        sn.rtnodes((ind - 1) * t.K + r, (jnd - 1) * t.K + s));
                    if (p > 0) {
                        touched[jnd - 1][s] = true;
                        SrcArr a;
                        a.snd = ind;
                        a.r = r;
                        a.qnd = jnd;
                        a.l = s;
                        src_arr.push_back(a);
                    }
                }
            }
        }
    }

    t.pidx.assign(t.I, std::vector<std::ptrdiff_t>(t.K, -1));
    std::size_t nm = 0;
    for (std::size_t pi = 0; pi < t.places.size(); ++pi) {
        const std::size_t ind = t.places[pi];
        for (std::size_t k = 0; k < t.K; ++k) {
            if (!(touched[ind - 1][k] || t.m0full[ind - 1][k] > 0)) continue;
            t.pidx[ind - 1][k] = static_cast<std::ptrdiff_t>(nm);
            t.coord_node.push_back(ind - 1);
            t.coord_class.push_back(k);
            t.coord_station.push_back(static_cast<std::ptrdiff_t>(sn.nodes[ind - 1].station) - 1);
            ++nm;
        }
    }
    t.nm = nm;

    // ---- the modes, and the phase coordinates of the multi-phase ones -------
    std::size_t nstate = nm;
    for (std::size_t ti = 0; ti < t.transitions.size(); ++ti) {
        const std::size_t ind = t.transitions[ti];
        const typename std::map<std::size_t, qn::TransitionParam<T>>::const_iterator it =
            sn.transparam.find(ind);
        if (it == sn.transparam.end()) continue;
        for (std::size_t m = 0; m < it->second.nmodes; ++m) {
            PetriMode rec = terms_detail::build_mode(sn, it->second, ind, m, t, nm);
            if (rec.nph > 1) {
                rec.zblk.resize(rec.nph);
                for (std::size_t h = 0; h < rec.nph; ++h) rec.zblk[h] = nstate + h;
                nstate += rec.nph;
            }
            t.modes.push_back(rec);
        }
    }
    t.nstate = nstate;
    // The phase coordinates are appended after every marking coordinate, so a
    // jump column built at nm width has to be GROWN once the total is known.
    for (std::size_t j = 0; j < t.modes.size(); ++j)
        if (t.modes[j].cvec.size() < nstate) t.modes[j].cvec.resize(nstate, 0.0);
    for (std::size_t j = 0; j < t.modes.size(); ++j) {
        if (t.modes[j].timing == lang::TimingStrategy::TIMED) t.timed_idx.push_back(j);
        else t.imm_idx.push_back(j);
    }

    // ---- the event columns --------------------------------------------------
    std::vector<std::vector<double>> cols;
    std::vector<double> rate_base;
    std::vector<int> ev_kind, ev_mode, ev_phase, ev_to;
    std::vector<std::ptrdiff_t> ev_station, ev_class;
    const auto emit = [&](const std::vector<double>& col, double base, int kind, int mode,
                          int phase, int to, std::ptrdiff_t station, std::ptrdiff_t cls) {
        cols.push_back(col);
        rate_base.push_back(base);
        ev_kind.push_back(kind);
        ev_mode.push_back(mode);
        ev_phase.push_back(phase);
        ev_to.push_back(to);
        ev_station.push_back(station);
        ev_class.push_back(cls);
    };

    for (std::size_t q = 0; q < t.timed_idx.size(); ++q) {
        const std::size_t j = t.timed_idx[q];
        const PetriMode& md = t.modes[j];
        if (md.nph == 1) {
            emit(md.cvec, md.d1[0], 1, static_cast<int>(j), 0, 0, -1, -1);
        } else {
            for (std::size_t h = 0; h < md.nph; ++h)
                for (std::size_t hp = 0; hp < md.nph; ++hp) {
                    const double w = md.D1(h, hp);
                    if (w <= 0) continue;
                    std::vector<double> col = md.cvec;
                    col[md.zblk[hp]] += 1.0;
                    col[md.zblk[h]] -= 1.0;
                    emit(col, w, 1, static_cast<int>(j), static_cast<int>(h),
                         static_cast<int>(hp), -1, -1);
                }
            for (std::size_t h = 0; h < md.nph; ++h)
                for (std::size_t hp = 0; hp < md.nph; ++hp) {
                    if (hp == h) continue;
                    const double w = md.D0(h, hp);
                    if (w <= 0) continue;
                    std::vector<double> col(nstate, 0.0);
                    col[md.zblk[hp]] = 1.0;
                    col[md.zblk[h]] = -1.0;
                    emit(col, w, 2, static_cast<int>(j), static_cast<int>(h),
                         static_cast<int>(hp), -1, -1);
                }
        }
    }
    // One latch column per multi-phase mode: mu_j servers per unit time enter at
    // the firing process's own entry distribution. The rate is FREE IN SIGN -- a
    // mode whose enabling degree drops stops servers rather than starting them --
    // and it is zero at any fixed point.
    for (std::size_t q = 0; q < t.timed_idx.size(); ++q) {
        const std::size_t j = t.timed_idx[q];
        const PetriMode& md = t.modes[j];
        if (md.nph <= 1) continue;
        std::vector<double> col(nstate, 0.0);
        for (std::size_t h = 0; h < md.nph; ++h) col[md.zblk[h]] = md.pie[h];
        emit(col, 1.0, 5, static_cast<int>(j), 0, 0, -1, -1);
    }
    for (std::size_t q = 0; q < t.imm_idx.size(); ++q) {
        const std::size_t j = t.imm_idx[q];
        emit(t.modes[j].cvec, 1.0, 4, static_cast<int>(j), 0, 0, -1, -1);
    }
    for (std::size_t a = 0; a < src_arr.size(); ++a) {
        const SrcArr& rec = src_arr[a];
        const std::size_t ist = sn.nodes[rec.snd - 1].station;
        if (ist >= 1 && ist <= sn.stations.size()) {
            const lang::ProcessType pt = sn.procid(ist, rec.r + 1);
            if (pt != lang::ProcessType::EXP)
                throw UnsupportedError(
                    "fluid_petri_terms: source " + t.names_node[rec.snd - 1] +
                    " has a non-exponential arrival for class " + std::to_string(rec.r + 1) +
                    ". The fluid Petri route models an arrival as a constant-propensity event, "
                    "which a renewal stream with memory is not; use SolverCTMC, SolverJMT or "
                    "SolverSSA");
        }
        std::vector<double> col(nstate, 0.0);
        col[static_cast<std::size_t>(t.pidx[rec.qnd - 1][rec.l])] = 1.0;
        const double base =
            num_traits<T>::to_double(sn.rates(ist - 1, rec.r)) *
            num_traits<T>::to_double(
                sn.rtnodes((rec.snd - 1) * t.K + rec.r, (rec.qnd - 1) * t.K + rec.l));
        emit(col, base, 3, -1, 0, 0, static_cast<std::ptrdiff_t>(ist) - 1,
             static_cast<std::ptrdiff_t>(rec.r));
    }

    t.nev = cols.size();
    t.D = Matrix<double>(nstate, std::max<std::size_t>(t.nev, 1), 0.0);
    for (std::size_t e = 0; e < t.nev; ++e)
        for (std::size_t s = 0; s < nstate; ++s)
            if (cols[e][s] != 0.0) t.D(s, e) = cols[e][s];
    t.rate_base = rate_base;
    t.ev_kind = ev_kind;
    t.ev_mode = ev_mode;
    t.ev_phase = ev_phase;
    t.ev_to = ev_to;
    t.ev_station = ev_station;
    t.ev_class = ev_class;

    // ---- which Sigma entries the closure reads ------------------------------
    std::map<std::pair<std::size_t, std::size_t>, std::size_t> pairkey;
    for (std::size_t j = 0; j < t.modes.size(); ++j) {
        const PetriMode& md = t.modes[j];
        if (md.closable)
            for (std::size_t a = 0; a < md.arc_slot.size(); ++a)
                for (std::size_t b = a; b < md.arc_slot.size(); ++b)
                    terms_detail::add_pair(pairkey, t.cov_pairs, md.arc_slot[a], md.arc_slot[b]);
        if (md.timing == lang::TimingStrategy::TIMED)
            for (std::size_t b = 0; b < md.inh_slot.size(); ++b)
                terms_detail::add_pair(pairkey, t.cov_pairs, md.inh_slot[b], md.inh_slot[b]);
    }
    t.npair = t.cov_pairs.size();
    const std::size_t pn = std::max<std::size_t>(nm, 1);
    t.pair_index.assign(pn, std::vector<std::ptrdiff_t>(pn, -1));
    for (std::size_t i = 0; i < t.npair; ++i) {
        t.pair_index[t.cov_pairs[i].first][t.cov_pairs[i].second] =
            static_cast<std::ptrdiff_t>(i);
        t.pair_index[t.cov_pairs[i].second][t.cov_pairs[i].first] =
            static_cast<std::ptrdiff_t>(i);
    }

    for (std::size_t e = 0; e < t.nev; ++e) {
        if (t.ev_kind[e] == 4) t.imm_col.push_back(e);
        else if (t.ev_kind[e] == 5) t.latch_col.push_back(e);
        if (t.ev_kind[e] != 4 && t.ev_kind[e] != 5) t.stoch_col.push_back(e);
    }
    for (std::size_t q = 0; q < t.timed_idx.size(); ++q)
        if (t.modes[t.timed_idx[q]].nph > 1) t.latch_mode.push_back(t.timed_idx[q]);
    t.cov_idx.resize(nstate);
    for (std::size_t s = 0; s < nstate; ++s) t.cov_idx[s] = s;

    // ---- per-place consumption and production, for the metric reader --------
    // A Place's throughput is the rate at which TOKENS leave it, so each
    // consuming mode contributes its firing rate times the multiplicity of the
    // arc it takes them through. That is SolverCTMC's convention and the one
    // Little's law needs; SolverSSA's NRM sums the UNWEIGHTED propensity, so the
    // two disagree wherever an input arc has multiplicity above one.
    for (std::size_t e = 0; e < t.nev; ++e) {
        if (t.ev_kind[e] == 3) {
            if (t.ev_station[e] < 0) continue;
            const std::size_t kk =
                static_cast<std::size_t>(t.ev_station[e]) * t.K +
                static_cast<std::size_t>(t.ev_class[e]);
            t.producers[kk].push_back(e);
            continue;
        }
        if (t.ev_kind[e] != 1 && t.ev_kind[e] != 4) continue;
        const PetriMode& md = t.modes[static_cast<std::size_t>(t.ev_mode[e])];
        for (std::size_t a = 0; a < md.arc_slot.size(); ++a) {
            const std::size_t s = md.arc_slot[a];
            if (t.coord_station[s] < 0) continue;
            const std::size_t kk =
                static_cast<std::size_t>(t.coord_station[s]) * t.K + t.coord_class[s];
            t.consumers[kk].push_back(e);
            t.consumer_w[kk].push_back(md.arc_w[a]);
        }
    }

    // ---- the initial state --------------------------------------------------
    t.x0.assign(nstate, 0.0);
    for (std::size_t s = 0; s < nm; ++s) t.x0[s] = t.m0full[t.coord_node[s]][t.coord_class[s]];
    for (std::size_t j = 0; j < t.modes.size(); ++j) {
        const PetriMode& md = t.modes[j];
        if (md.nph <= 1) continue;
        double e = std::numeric_limits<double>::infinity();
        for (std::size_t a = 0; a < md.arc_slot.size(); ++a)
            e = std::min(e, t.x0[md.arc_slot[a]] / md.arc_w[a]);
        if (md.arc_slot.empty()) e = 1.0;
        for (std::size_t h = 0; h < md.nph; ++h) t.x0[md.zblk[h]] = std::min(e, md.c) * md.pie[h];
    }
    return t;
}

