std::vector<Citation> line_citations(const std::vector<std::string>& tokens) {
    const std::map<std::string, Citation>& reg = citation_registry();
    std::vector<Citation> out;
    std::set<std::string> seen;
    for (const std::string& raw : tokens) {
        const std::string t = normalise(raw);
        if (t.empty()) continue;
        auto it = reg.find(t);
        if (it == reg.end()) {
            // A family-qualified method name falls back to the bare method name, so
            // `nc.mva` finds `mva` when the qualified form is absent.
            const std::size_t dot = t.find('.');
            if (dot == std::string::npos) continue;
            it = reg.find(t.substr(dot + 1));
            if (it == reg.end()) continue;
        }
        // One paper is often reachable through several tokens; report it once.
        if (!seen.insert(it->second.key).second) continue;
        out.push_back(it->second);
    }
    return out;
}

std::vector<Citation> line_citations_for_method(const std::string& method) {
    std::vector<std::string> parts;
    std::size_t b = 0;
    while (b <= method.size()) {
        const std::size_t s = method.find('/', b);
        parts.push_back(method.substr(b, s == std::string::npos ? std::string::npos : s - b));
        if (s == std::string::npos) break;
        b = s + 1;
    }
    return line_citations(parts);
}

